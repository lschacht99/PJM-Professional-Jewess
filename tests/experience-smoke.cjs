const {chromium}=require('playwright');const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const errors=[],posts=[];
 try{
  const page=await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('fonts.googleapis'))errors.push(m.text())});
  await page.route('https://vvveenntewwtyhnmimal.supabase.co/rest/v1/**',async route=>{posts.push({url:route.request().url(),data:JSON.parse(route.request().postData()||'{}')});await route.fulfill({status:201,body:'',headers:{'access-control-allow-origin':'*'}})});
  await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.match(await page.locator('h1').innerText(),/Find out what a career/i);
  assert.equal(await page.locator('#jd-feature-title').innerText(),'The Impossible Sukkah.');
  assert.ok(await page.locator('header a.header-pro').getAttribute('href')==='partners.html#professionals');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile no overflow');
  assert.equal(await page.locator('#jd-ideas .jd-idea').count(),2);
  assert.equal(await page.locator('[data-jd-tab=conversations]').getAttribute('aria-selected'),'true','professional conversations initially selected');
  assert.equal(await page.locator('#jd-ideas .jd-idea-pro').count(),2,'both ideas describe professional conversations');
  assert.match(await page.locator('#jd-ideas .jd-idea-pro').first().innerText(),/working engineer/i);
  assert.equal(await page.locator('#jd-mail-form').count(),1);
  assert.equal(await page.locator('input[name=email]').count(),1);
  assert.equal(await page.locator('.jd-feature').count(),1);
  assert.equal(await page.locator('.jd-feature-reveal').getAttribute('open'),null,'featured engineering mission initially collapsed');
  assert.equal(await page.locator('.jd-feature-expanded').isVisible(),false,'hide full mission by default');
  assert.ok(await page.locator('a[href="partners.html#professionals"].jd-btn').count()===1,'professional CTA visible in hero');
  const pro=await page.locator('a[href="partners.html#professionals"].jd-btn').boundingBox();
  assert.ok(pro&&pro.y+pro.height<=812,'early professional action visible before scroll');
  assert.equal(await page.locator('.jd-hero-hint').count(),0,'remove extra list of professions under hero');
  await page.locator('.jd-feature-reveal summary').click();
  assert.equal(await page.locator('.jd-feature-expanded').isVisible(),true,'expand practical engineering brief');
  assert.match(await page.locator('.jd-feature-expanded').innerText(),/fan|wind test/i);
  assert.match(await page.locator('.jd-feature-expanded').innerText(),/engineer reviews|engineer/i,'engineering Q&A described');
  await page.locator('.jd-feature-reveal summary').click();
  assert.equal(await page.locator('.jd-feature-expanded').isVisible(),false,'collapse back to compact teaser');
  await page.locator('[data-jd-tab=tech]').click();
  assert.match(await page.locator('#jd-category-name').innerText(),/TECHNOLOGY/);
  assert.equal(await page.locator('#jd-ideas .jd-idea').count(),2);
  await page.locator('#jd-ideas .jd-save').first().click();
  assert.equal(await page.locator('#jd-shortlist-bar').isVisible(),true);
  assert.match(await page.locator('#jd-shortlist-count').innerText(),/1 saved/);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.match(await page.locator('#jd-shortlist-count').innerText(),/1 saved/,'shortlist persists after refresh');
  await page.locator('#jd-review').click();
  assert.equal(await page.locator('#jd-sheet[open]').count(),1,'shortlist drawer opens');
  assert.match(await page.locator('#jd-selection').innerText(),/Spreadsheet Is Lying/);
  await page.locator('#jd-email').fill('qa@example.invalid');
  await page.locator('#jd-mail-form input[name=consent]').check();
  await page.locator('#jd-mail-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#jd-mail-state')?.textContent?.startsWith('Thanks.'));
  assert.equal(posts.length,1);
  assert.ok(posts[0].url.endsWith('pj_interest_shortlists'));
  assert.deepEqual(posts[0].data.idea_ids,['data-detective']);
  assert.equal(posts[0].data.email,'qa@example.invalid');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#jd-sheet[open]').count(),0);
  await page.locator('.jd-feature-reveal summary').click();
  await page.locator('[data-jd-open=sukkah]').first().click();
  assert.match(await page.locator('#jd-selection').innerText(),/Impossible Sukkah/);
  await page.locator('#jd-email').fill('qa2@example.invalid');
  await page.locator('#jd-mail-form input[name=consent]').check();
  await page.locator('#jd-mail-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#jd-mail-state')?.textContent?.startsWith('Thanks.'));
  assert.equal(posts.length,2,'direct expression of interest does not require save');
  assert.deepEqual(posts[1].data.idea_ids,['impossible-sukkah']);
  await page.keyboard.press('Escape');
  await page.goto('http://127.0.0.1:8765/partners.html#professionals',{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('#professionals').count(),1,'professional shortcut landing exists');
  await page.goto('http://127.0.0.1:8765/opportunities.html#library',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('[data-jm-library] .jm-experience-card');
  assert.ok((await page.locator('[data-jm-library] .jm-experience-card').count())>=20,'full library preserved');
  assert.equal(await page.locator('.jm-card-brief').count(),26,'each experience reveals a concrete activity');
  assert.equal(await page.locator('[data-jm-format-filter]').count(),1,'format filter visible');
  await page.selectOption('#jm-format-filter','conversation');
  assert.equal(await page.locator('.jm-experience-card').count(),8,'eight professional conversations');
  assert.match(await page.locator('.jm-experience-card').first().innerText(),/CAREER CONVERSATION/i);
  await page.selectOption('#jm-library-filter','Engineering');
  assert.equal(await page.locator('.jm-experience-card').count(),1,'one engineering professional conversation');
  await page.selectOption('#jm-format-filter','project');
  assert.equal(await page.locator('.jm-experience-card').count(),3,'three engineering projects with professional input');
  await page.selectOption('#jm-format-filter','All');
  await page.selectOption('#jm-library-filter','All');
  assert.equal(await page.locator('.jm-experience-card').count(),26);
  assert.equal(await page.locator('.jm-card-brief').first().getAttribute('open'),null,'missions collapsed initially');
  await page.locator('.jm-card-brief summary').first().click();
  assert.equal(await page.locator('.jm-card-brief').first().locator('p').isVisible(),true);
  assert.equal(await page.locator('.jm-card-pro').count(),26,'every concept has a professional connection');
  const desktop=await browser.newPage({viewport:{width:1280,height:900}});
  desktop.on('pageerror',e=>errors.push('desktop '+e.message));
  await desktop.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
  await desktop.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.ok(await desktop.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'desktop no overflow');
  assert.equal(await desktop.locator('.jd-feature').isVisible(),true);
  assert.deepEqual(errors,[],'no JavaScript errors');
  console.log('PASS: compact engineering brief, above-fold professional CTA, refreshed challenge library, wishlist, privacy and mock submissions.');
 }finally{await browser.close()}
})().catch(e=>{console.error('FAILED',e);process.exitCode=1});
