const {chromium}=require('playwright');const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const errors=[],posts=[];
 try{
  const page=await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('fonts.googleapis'))errors.push(m.text())});
  await page.route('https://vvveenntewwtyhnmimal.supabase.co/rest/v1/**',async route=>{posts.push({url:route.request().url(),data:JSON.parse(route.request().postData()||'{}')});await route.fulfill({status:201,body:'',headers:{'access-control-allow-origin':'*'}})});
  await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.match(await page.locator('h1').innerText(),/Find out what a career/i);
  assert.equal(await page.locator('#jd-feature-title').innerText(),'Shabbos, Anywhere.');
  assert.ok(await page.locator('header a.header-pro').getAttribute('href')==='partners.html#professionals');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile no overflow');
  assert.equal(await page.locator('#jd-ideas .jd-idea').count(),2);
  assert.equal(await page.locator('#jd-mail-form').count(),1);
  assert.equal(await page.locator('input[name=email]').count(),1);
  assert.equal(await page.locator('.jd-feature').count(),1);
  await page.locator('[data-jd-tab=tech]').click();
  assert.match(await page.locator('#jd-category-name').innerText(),/TECHNOLOGY/);
  assert.equal(await page.locator('#jd-ideas .jd-idea').count(),2);
  await page.locator('#jd-ideas .jd-save').first().click();
  assert.equal(await page.locator('#jd-shortlist-bar').isVisible(),true);
  assert.match(await page.locator('#jd-shortlist-count').innerText(),/1 saved/);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.match(await page.locator('#jd-shortlist-count').innerText(),/1 saved/,'shortlist persists after refresh');
  await page.locator('#jd-review').click();
  assert.equal(await page.locator('#jd-sheet[open]').count(),1,'shortlist drawer opens');
  assert.match(await page.locator('#jd-selection').innerText(),/Data Detective/);
  await page.locator('#jd-email').fill('qa@example.invalid');
  await page.locator('#jd-mail-form input[name=consent]').check();
  await page.locator('#jd-mail-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#jd-mail-state')?.textContent?.startsWith('Thanks.'));
  assert.equal(posts.length,1);
  assert.ok(posts[0].url.endsWith('pj_interest_shortlists'));
  assert.deepEqual(posts[0].data.idea_ids,['data-detective']);
  assert.equal(posts[0].data.email,'qa@example.invalid');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#jd-sheet[open]').count(),0);
  await page.locator('[data-jd-open=shabbos]').first().click();
  assert.match(await page.locator('#jd-selection').innerText(),/Shabbos, Anywhere/);
  await page.locator('#jd-email').fill('qa2@example.invalid');
  await page.locator('#jd-mail-form input[name=consent]').check();
  await page.locator('#jd-mail-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#jd-mail-state')?.textContent?.startsWith('Thanks.'));
  assert.equal(posts.length,2,'direct expression of interest does not require save');
  assert.deepEqual(posts[1].data.idea_ids,['shabbos-anywhere']);
  await page.keyboard.press('Escape');
  await page.goto('http://127.0.0.1:8765/partners.html#professionals',{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('#professionals').count(),1,'professional shortcut landing exists');
  await page.goto('http://127.0.0.1:8765/opportunities.html#library',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('[data-jm-library] .jm-experience-card');
  assert.ok((await page.locator('[data-jm-library] .jm-experience-card').count())>=20,'full library preserved');
  const desktop=await browser.newPage({viewport:{width:1280,height:900}});
  desktop.on('pageerror',e=>errors.push('desktop '+e.message));
  await desktop.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
  await desktop.waitForFunction(()=>document.documentElement.dataset.jdReady==='true');
  assert.ok(await desktop.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'desktop no overflow');
  assert.equal(await desktop.locator('.jd-feature').isVisible(),true);
  assert.deepEqual(errors,[],'no JavaScript errors');
  console.log('PASS: mobile-first challenge, professional shortcut, tabs, local shortlist persistence, single idea and multi-idea simulated requests, partner link.');
 }finally{await browser.close()}
})().catch(e=>{console.error('FAILED',e);process.exitCode=1});
